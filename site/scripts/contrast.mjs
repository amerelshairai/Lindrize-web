/**
 * Colour contrast check (WCAG 2.2 AA). Reads the colour tokens from global.css and tests every
 * text-on-background pair the site uses, in light and dark mode.
 *   node scripts/contrast.mjs            fails if any pair is below the standard
 *   node scripts/contrast.mjs --write    also writes the table to docs/CONTRAST.md
 * Rules: 4.5:1 for normal text, 3:1 for large text (24px+) and for the edges of controls.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const css = readFileSync(fileURLToPath(new URL('../src/styles/global.css', import.meta.url)), 'utf8');
const block = (selector) => {
  const start = css.indexOf(selector);
  if (start < 0) throw new Error(`Cannot find ${selector} in global.css`);
  const body = css.slice(css.indexOf('{', start) + 1, css.indexOf('}', start));
  return Object.fromEntries([...body.matchAll(/--([\w-]+):\s*(#[0-9a-fA-F]{6})/g)].map((m) => [m[1], m[2]]));
};
const light = block(':root {');
const themes = { Light: light, Dark: { ...light, ...block(":root[data-theme='dark']") } };

const luminance = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

// [what it is, foreground token, background token, minimum]
const PAIRS = [
  ['Body text and headings', 'ink', 'bg', 4.5],
  ['Body text on soft panels', 'ink', 'soft', 4.5],
  ['Secondary text', 'muted', 'bg', 4.5],
  ['Secondary text on soft panels (footer, chat)', 'muted', 'soft', 4.5],
  ['Main button label on teal', 'on-teal', 'teal', 4.5],
  ['Main button label on teal, pointed at', 'on-teal', 'teal-hover', 4.5],
  ['Assistant chat bubble text', 'agent-ink', 'agent', 4.5],
  ['Assistant chat bubble time', 'agent-meta', 'agent', 4.5],
  ['Selected choice (label on dark fill)', 'bg', 'ink', 4.5],
  ['Unlit words in the scrolling statement (large text)', 'line-strong', 'bg', 3],
  ['Edges of buttons, inputs and choices', 'line-strong', 'bg', 3],
  ['Edges of controls on soft panels', 'line-strong', 'soft', 3],
  ['Keyboard focus outline', 'ink', 'bg', 3],
  ['Teal button against the page', 'teal', 'bg', 1],
];

const rows = [];
let failed = false;
for (const [theme, t] of Object.entries(themes)) {
  for (const [what, fg, bg, min] of PAIRS) {
    const value = ratio(t[fg], t[bg]);
    const ok = value >= min;
    if (!ok) failed = true;
    rows.push({ theme, what, fg: t[fg], bg: t[bg], value, min, ok });
  }
}
for (const r of rows.filter((r) => !r.ok)) console.error(`✗ ${r.theme}: ${r.what} is ${r.value.toFixed(2)}:1, needs ${r.min}:1 (${r.fg} on ${r.bg})`);
if (!failed) console.log(`✓ Colour contrast: ${rows.length} pairs meet WCAG 2.2 AA in light and dark mode`);

if (process.argv.includes('--write')) {
  const table = (theme) =>
    ['| Used for | Colour | On | Contrast | Needs | Result |', '|---|---|---|---|---|---|',
      ...rows.filter((r) => r.theme === theme).map((r) => `| ${r.what} | \`${r.fg}\` | \`${r.bg}\` | ${r.value.toFixed(2)}:1 | ${r.min === 1 ? 'not text' : `${r.min}:1`} | ${r.min === 1 ? 'see note' : r.ok ? 'Pass' : 'FAIL'} |`),
    ].join('\n');
  const md = `# Colour contrast

Generated by \`site/scripts/contrast.mjs\` from the colour tokens in \`site/src/styles/global.css\`.
The same script runs in the checks and fails if any pair drops below the standard.

Standard (WCAG 2.2 AA): 4.5:1 for normal text, 3:1 for large text (24px and up) and for the
edges of controls.

## Light mode

${table('Light')}

## Dark mode

${table('Dark')}

## Note on teal

Teal is never used for text. It is the fill of the main buttons, and the button's label (dark
text on teal) is what must be readable. A teal button is also recognisable by its shape, size and
label, so its fill is not required to reach 3:1 against the page.
`;
  writeFileSync(fileURLToPath(new URL('../../docs/CONTRAST.md', import.meta.url)), md);
  console.log('Wrote docs/CONTRAST.md');
}
process.exit(failed ? 1 : 0);
